"""
quench_sweep.py
=================
For each location on the coil, finds the current at which that
location's actual transport current would exceed its local critical
current Ic(B, theta) -- using B interpolated LINEARLY between several
actual FEM solves (from solve_sweep.py's sweep_currents), never
extrapolated beyond them, and the Ic(B, theta) model's own linear,
hard-clamped interpolation (see physics/ic_model.py) so the reported
critical current can never exceed what the manufacturer's table
actually shows.

Why several real solves instead of one solve + analytic scaling:
this magnetostatics problem (mu0 everywhere, no magnetic materials) is
in fact exactly linear in the current, so one solve plus scaling would
give the identical answer up to FEM/solver tolerance. But solving
independently at each current in params.sweep_currents avoids relying
on that argument at all, and is what was asked for -- each
sweep/field_sweep/I_*.npz is a genuine, separate FEM solve, not a
rescaled copy.

The angle to the tape's out-of-plane vector is recomputed from each
solve's own B vector (not assumed constant), then also linearly
interpolated across the solved currents along with |B| -- so both
inputs to the Ic model come from the same real-data interpolation.

Outputs (data in sweep/, plots in visualization/):
  - sweep/quench_results.csv     : per-location data
  - sweep/quench_summary.txt     : weakest point, distribution stats
  - visualization/ic_landscape.png    : where the coil's operating
                                          points sit on the Ic(B,theta)
                                          surface

  quench_3d.png and quench_2d.png are generated by plot_3d.py (run
  separately after this script, using sweep/quench_results.csv).

Run after solve_sweep.py (or after make_test_data.py for a synthetic
test of this script alone):
    python3 quench_sweep.py
"""
